def rec(system, seed, size, field='tipo'):
    """Metrics of one system/seed/size/field, or None if not run."""
    if system == 'base':
        t = base['semi'].get(seed, {}).get(size)
    else:
        t = ft[system][seed].get(size)
    return None if t is None else t['campi'][field]


def seeds_run(system, size):
    return [s for s in SEEDS if rec(system, s, size) is not None]


def mean(xs):
    return sum(xs) / len(xs)


def val(system, size, field='tipo', metric='accuracy', seeds=None):
    ss = seeds if seeds is not None else seeds_run(system, size)
    if not ss:
        return None
    return mean([rec(system, s, size, field)[metric] for s in ss])


def sw(system, size, seeds=None, metric='accuracy'):
    """Mean of the three switches, averaged over seeds."""
    ss = seeds if seeds is not None else seeds_run(system, size)
    if not ss:
        return None
    return mean([mean([rec(system, s, size, f)[metric] for f in SWITCHES]) for s in ss])


def band(system, size, getter):
    ss = seeds_run(system, size)
    vs = [getter(system, size, [s]) for s in ss]
    return (min(vs), max(vs)) if vs else None


def pts(x):
    return f'{100 * x:+.1f}'.replace('-', '$-$')


def f3(x):
    return '--' if x is None else f'{x:.3f}'


def wilson(p, n, z=1.96):
    c = (p + z * z / (2 * n)) / (1 + z * z / n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return c - h, c + h


