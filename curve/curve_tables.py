hyp.append(('H5$^{c}$', 'Offer and spam F1 $<$0.3 for every trained system, seed and budget',
            f'{len(against)} of {cases} cases $\\geq$0.3 (all fine-tunes; baseline max {base_rare_max:.2f})',
            'confirmed' if H5 else 'refuted'))
